/**
 * Scan page text for facility keywords and return matches with confidence & evidence
 */
export const extractFacilitiesFromPage = (text, pageUrl, pageType) => {
  if (!text) return {};
  
  const results = {};
  const lines = text.split("\n").map(l => l.trim()).filter(Boolean);
  const pageTypeLower = (pageType || "").toLowerCase();

  for (const [facility, keywords] of Object.entries(FACILITY_KEYWORDS)) {
    let matched = false;
    let confidence = 0;
    let evidenceText = "";
    let matchedKeyword = "";
    let matchedType = "";

    // 1. Check primary keywords
    for (const kw of keywords.primary) {
      const escapedKw = kw.replace(/[-\/\\^$*+?.()|[\]{}]/g, "\\$&");
      const regex = new RegExp(`\\b${escapedKw}\\b`, "i");
      
      const matchLine = lines.find(line => regex.test(line));
      if (matchLine) {
        matched = true;
        confidence = 90;
        evidenceText = matchLine;
        matchedKeyword = kw;
        matchedType = "primary";
        break;
      }
    }

    // 2. Check secondary keywords if not matched by primary
    if (!matched) {
      for (const kw of keywords.secondary) {
        const escapedKw = kw.replace(/[-\/\\^$*+?.()|[\]{}]/g, "\\$&");
        const regex = new RegExp(`\\b${escapedKw}\\b`, "i");
        
        const matchLine = lines.find(line => regex.test(line));
        if (matchLine) {
          matched = true;
          confidence = 75;
          evidenceText = matchLine;
          matchedKeyword = kw;
          matchedType = "secondary";
          break;
        }
      }
    }

    if (matched) {
      // Page specificity boost (+5)
      let isSpecificPage = false;
      
      if (facility === "library" || facility === "digitalLibrary") {
        isSpecificPage = pageTypeLower.includes("library");
      } else if (facility === "hostelBoys" || facility === "hostelGirls") {
        isSpecificPage = pageTypeLower.includes("hostel");
      } else if (facility === "sports" || facility === "gym") {
        isSpecificPage = pageTypeLower.includes("sports") || pageTypeLower.includes("gym");
      } else {
        isSpecificPage = pageTypeLower.includes(facility.toLowerCase()) || 
                         pageTypeLower.includes("facility") || 
                         pageTypeLower.includes("infrastructure");
      }

      if (isSpecificPage) {
        confidence += 5;
      }

      results[facility] = {
        detected: true,
        confidence,
        evidence: {
          text: evidenceText,
          sourceUrl: pageUrl,
          matchedKeyword,
          matchedType
        }
      };
    }
  }

  return results;
};
